int map_count(void)
{
    return (int)(sizeof(MAP_LIST) / sizeof(MAP_LIST[0]));
}   

const Map *get_map(int index)
{
    if (index < 0 || index >= map_count())
    {
        return NULL;
    }

    return &MAP_LIST[index];
}
